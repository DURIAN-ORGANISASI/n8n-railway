#!/usr/bin/env python3
"""Offline checks for the n8n Railway deployment starter."""
from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REQUIRED_FILES = [
    ".dockerignore",
    ".env.example",
    ".gitignore",
    ".github/workflows/validate.yml",
    "CONTRIBUTING.md",
    "Dockerfile",
    "FILE-MANIFEST.json",
    "LICENSE",
    "README.md",
    "README.en.md",
    "SECURITY.md",
    "docs/SOURCES.md",
    "docs/architecture.svg",
    "docker-compose.local.yml",
    "n8n-service-variables.example.txt",
    "railway.json",
    "scripts/check_docs.py",
    "scripts/validate-repo.py",
    "scripts/update-manifest.py",
    "scripts/generate-key.ps1",
    "scripts/generate-key.sh",
]
errors: list[str] = []

for relative_path in REQUIRED_FILES:
    if not (ROOT / relative_path).is_file():
        errors.append(f"Missing required file: {relative_path}")


def read_text(relative_path: str) -> str:
    path = ROOT / relative_path
    return path.read_text(encoding="utf-8") if path.is_file() else ""


try:
    railway = json.loads(read_text("railway.json"))
    if railway.get("build", {}).get("dockerfilePath") != "Dockerfile":
        errors.append("railway.json must point to Dockerfile at repository root")
    if railway.get("deploy", {}).get("healthcheckPath") != "/healthz":
        errors.append("Expected n8n healthcheck path /healthz")
except (json.JSONDecodeError, OSError) as exc:
    errors.append(f"railway.json is invalid: {exc}")

variables = read_text("n8n-service-variables.example.txt")
for name in (
    "N8N_ENCRYPTION_KEY",
    "WEBHOOK_URL",
    "DB_TYPE",
    "DB_POSTGRESDB_HOST",
    "DB_POSTGRESDB_PASSWORD",
):
    if not re.search(rf"(?m)^{name}=", variables):
        errors.append(f"Missing required Railway variable example: {name}")
if "REPLACE_WITH_YOUR_64_CHARACTER_HEX_KEY" not in variables:
    errors.append("Encryption key placeholder missing from Railway variable template")
if "DO NOT paste this file into the Postgres service" not in variables:
    errors.append("The Railway variable template must say it is for the n8n service only")

local_env = read_text(".env.example")
if "POSTGRES_PASSWORD=" not in local_env or "N8N_ENCRYPTION_KEY=" not in local_env:
    errors.append(".env.example must provide placeholders for the local database password and n8n key")
if "REPLACE_WITH_" not in local_env:
    errors.append(".env.example must use obvious secret placeholders, not real credentials")

readme = read_text("README.md")
postgres_step = readme.find("1. **Buat project dan PostgreSQL.**")
n8n_deploy_step = readme.find("3. **Deploy n8n.**")
if postgres_step < 0 or n8n_deploy_step < 0 or postgres_step > n8n_deploy_step:
    errors.append("README must instruct users to create PostgreSQL before deploying n8n")
if "jangan membuat atau menempelkan variabel database secara manual" not in readme:
    errors.append("README must explain PostgreSQL variables are generated by Railway")

readme_en = read_text("README.en.md")
if "## Sources, attribution, and licensing" not in readme_en:
    errors.append("English README must include source attribution and license scope")
if "docs/architecture.svg" not in readme or "docs/architecture.svg" not in readme_en:
    errors.append("Both READMEs must use the validated architecture diagram")
if "N8N_ENCRYPTION_KEY" not in readme or "N8N_ENCRYPTION_KEY" not in readme_en:
    errors.append("Both READMEs must explain the n8n encryption key")
if "RAILWAY_RUN_UID=0" not in readme or "runs the process as root" not in readme_en.lower():
    errors.append("Both READMEs must explain the root-run volume-permission workaround")

license = read_text("LICENSE")
if not license.startswith("MIT License") or "Copyright (c) 2026 n8n Railway Starter contributors" not in license:
    errors.append("The existing project MIT license header/copyright notice is missing")

dockerfile = read_text("Dockerfile")
if not re.search(r"(?m)^ARG N8N_VERSION=\d+\.\d+\.\d+\s*$", dockerfile):
    errors.append("Dockerfile should pin N8N_VERSION to a numeric release tag")

if re.search(r"(?i)(sk-[a-z0-9]{20,}|ghp_[a-z0-9]{20,}|password\s*=\s*[^R$#\s][^\s]*)", variables):
    errors.append("Possible secret detected in the Railway variable example")

if "docs/SOURCES.md" not in readme or "docs/SOURCES.md" not in readme_en:
    errors.append("Both READMEs must link to docs/SOURCES.md")
if "MIT does not" not in readme_en and "does not" not in readme_en:
    errors.append("English README must explain that the root MIT license does not relicense n8n")

manifest_check = subprocess.run(
    [sys.executable, str(ROOT / "scripts" / "update-manifest.py"), "--check"],
    capture_output=True,
    text=True,
    check=False,
)
if manifest_check.returncode != 0:
    detail = manifest_check.stderr.strip() or manifest_check.stdout.strip()
    errors.append(f"FILE-MANIFEST.json check failed: {detail}")

if errors:
    print("Validation FAILED:")
    for error in errors:
        print(f"- {error}")
    sys.exit(1)

print("Validation OK: required files, Railway JSON, environment examples, source attribution, and pinned n8n tag look valid.")
print("This is a static check only; it does not prove that a Railway deployment or database connection will succeed.")
