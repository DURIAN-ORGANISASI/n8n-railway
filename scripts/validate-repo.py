#!/usr/bin/env python3
"""Lightweight offline checks for the n8n Railway starter repository."""
from pathlib import Path
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
required = [
    "Dockerfile", "railway.json", "n8n-service-variables.example.txt",
    "README.md", ".env.example", "docker-compose.local.yml", "LICENSE",
    "docker-compose.local.yml", "scripts/generate-key.ps1", "scripts/generate-key.sh"
]
errors = []
for rel in required:
    if not (ROOT / rel).is_file():
        errors.append(f"Missing required file: {rel}")

try:
    railway = json.loads((ROOT / "railway.json").read_text(encoding="utf-8"))
    if railway.get("build", {}).get("dockerfilePath") != "Dockerfile":
        errors.append("railway.json must point to Dockerfile at repository root")
    if railway.get("deploy", {}).get("healthcheckPath") != "/healthz":
        errors.append("Expected n8n healthcheck path /healthz")
except Exception as exc:
    errors.append(f"railway.json is invalid: {exc}")

variables = (ROOT / "n8n-service-variables.example.txt").read_text(encoding="utf-8") if (ROOT / "n8n-service-variables.example.txt").exists() else ""
for name in ("N8N_ENCRYPTION_KEY", "WEBHOOK_URL", "DB_TYPE", "DB_POSTGRESDB_HOST", "DB_POSTGRESDB_PASSWORD"):
    if not re.search(rf"(?m)^{name}=", variables):
        errors.append(f"Missing required Railway variable example: {name}")
if "REPLACE_WITH_YOUR_64_CHARACTER_HEX_KEY" not in variables:
    errors.append("Encryption key placeholder missing from variable template")
if "DO NOT paste this file into the Postgres service" not in variables:
    errors.append("The Railway variables template must clearly say it is for n8n only")
readme = (ROOT / "README.md").read_text(encoding="utf-8") if (ROOT / "README.md").exists() else ""
postgres_step = readme.find("1. **Buat project dan PostgreSQL.**")
n8n_deploy_step = readme.find("3. **Deploy n8n.**")
if postgres_step < 0 or n8n_deploy_step < 0 or postgres_step > n8n_deploy_step:
    errors.append("README must instruct users to create PostgreSQL before deploying n8n")
if "jangan membuat atau menempelkan variabel database secara manual" not in readme:
    errors.append("README must explain PostgreSQL variables are generated by Railway")

dockerfile = (ROOT / "Dockerfile").read_text(encoding="utf-8") if (ROOT / "Dockerfile").exists() else ""
if not re.search(r"(?m)^ARG N8N_VERSION=\d+\.\d+\.\d+\s*$", dockerfile):
    errors.append("Dockerfile should pin N8N_VERSION to a numeric release tag")
if re.search(r"(?i)(sk-[a-z0-9]{20,}|ghp_[a-z0-9]{20,}|password\s*=\s*[^R$#\s][^\s]*)", variables):
    errors.append("Possible secret detected in variable example")

if errors:
    print("Validation FAILED:")
    for error in errors:
        print(f"- {error}")
    sys.exit(1)

print("Validation OK: required files, Railway JSON, core variables, and pinned n8n tag look valid.")
print("This is a static check only; it does not prove that a Railway deployment or database connection will succeed.")
